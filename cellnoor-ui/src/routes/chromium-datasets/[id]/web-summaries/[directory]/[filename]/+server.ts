import { getApiClient, reauthenticate } from "$lib/server/cellnoor-client";
import { readConfig } from "$lib/server/config";
import type { RequestHandler } from "./$types";

// It would be faster to just grab the web summary from the database and send
// it directly. However, that requires us to implement an authorization check here and grant cellnoor-ui permission to
// read at least one table. I don't want to do that because the logic is implemented in Rust (bulletproof) already and
// I don't trust myself in this infernal language.

export async function GET({ fetch, params: { id, directory, filename } }) {
  // It'd be nice to use the `CellnoorClient` here, but the Rust library used to generate the OpenAPI document doesn't support HTML as a content type I guess? So the resulting client generated by openapi-ts doesn't have that route either
  await reauthenticate();
  const url = await readConfig().then((c) =>
    `${c.apiUrl}/chromium-datasets/${id}/web-summaries/${directory}/${filename}`
  );

  console.log(url);

  return fetch(url);
}
